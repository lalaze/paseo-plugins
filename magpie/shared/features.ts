export const readFeature = defineRpc({
  name: "magpie.feature.read",
  input: z.object({
    feature: z.enum(Object.keys(featureRoutes) as [Feature, ...Feature[]]),
    query: z.record(z.string(), z.string()).default({}),
  }),
  output: z.object({ data: z.json() }),
});
export const featureAction = z.object({
  type: z.literal("feature"),
  operation: z.enum(Object.keys(operationRoutes) as [Operation, ...Operation[]]),
  body: z.record(z.string(), z.json()).default({}),
});
export const mutateFeature = defineRpc({
  name: "magpie.feature.mutate",
  input: featureAction.omit({ type: true }),
  output: z.object({ data: z.json(), jobId: z.string().default("") }),
});
export type Json = z.infer<ReturnType<typeof z.json>>;
export type Row = Record<string, Json>;
